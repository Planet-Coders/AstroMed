import { PrismaClient, Role } from "@prisma/client";
import bcrypt from "bcryptjs";
import { PROFILES, generate } from "../lib/monitoring/synthetic";

/**
 * Seeds a clearly labelled SYNTHETIC test crew (group SIM-1) with 14–30 days of records:
 * one astronaut per profile (normal, missing data, sleep debt, rising heart rate,
 * dehydration, solar particle event). Re-running replaces their data.
 *
 *   npm run db:synthetic -- --days 30 --seed 1
 */

const prisma = new PrismaClient();

function arg(name: string, fallback: number) {
  const i = process.argv.indexOf(`--${name}`);
  const v = i >= 0 ? Number(process.argv[i + 1]) : NaN;
  return Number.isFinite(v) ? v : fallback;
}

async function main() {
  const days = Math.min(30, Math.max(14, arg("days", 30)));
  const seed = arg("seed", 1);
  const now = Date.now();
  const password = await bcrypt.hash("aahms2025", 10);

  const group = await prisma.missionGroup.upsert({
    where: { code: "SIM-1" },
    update: {},
    create: {
      code: "SIM-1",
      name: "Synthetic test crew",
      destination: "Simulation",
      description: "SYNTHETIC DATA generated by prisma/synthetic.ts for testing alerts and dashboards. Not real astronauts.",
    },
  });

  for (const p of PROFILES) {
    const email = `sim-${p.id.replace(/_/g, "-")}@aahms.demo`;
    const user = await prisma.user.upsert({
      where: { email },
      update: { name: p.name, callsign: p.callsign, groupId: group.id, crewId: group.code, synthetic: true, role: Role.ASTRONAUT },
      create: { email, name: p.name, callsign: p.callsign, password, role: Role.ASTRONAUT, crewId: group.code, groupId: group.id, synthetic: true },
    });

    // Fresh data each run: old synthetic records, and alerts raised from them.
    await prisma.$transaction([
      prisma.metricSample.deleteMany({ where: { userId: user.id } }),
      prisma.biometricRecord.deleteMany({ where: { userId: user.id } }),
      prisma.alert.deleteMany({ where: { userId: user.id } }),
    ]);

    const { samples, vitals } = generate(p.id, days, now, seed);
    await prisma.metricSample.createMany({
      data: samples.map((s, i) => ({
        id: `syn-${user.id}-${i}`,
        userId: user.id,
        metric: s.metric,
        value: s.value,
        recordedAt: new Date(s.at),
        source: "synthetic",
        synthetic: true,
        detail: s.detail,
      })),
    });
    await prisma.biometricRecord.createMany({
      data: vitals.map((v, i) => ({
        id: `syn-${user.id}-v${i}`,
        userId: user.id,
        heartRate: v.heartRate,
        hrv: v.hrv,
        spo2: v.spo2,
        radiation: v.radiation,
        synced: true,
        timestamp: new Date(v.at),
      })),
    });
    console.log(`${p.name.padEnd(16)} ${email.padEnd(32)} ${samples.length} log samples, ${vitals.length} vitals · ${p.summary}`);
  }

  // Let the seeded flight surgeon follow the test crew.
  await prisma.user
    .update({ where: { email: "surgeon@aahms.demo" }, data: { overseenGroups: { connect: { id: group.id } } } })
    .catch(() => console.warn("surgeon@aahms.demo not found; assign SIM-1 to an oversight user in /admin."));

  console.log(`Synthetic crew SIM-1 ready: ${days} days, seed ${seed}. Crew password aahms2025 (any password in demo mode).`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
